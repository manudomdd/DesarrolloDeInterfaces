    public void mostrarFechaActual() {
        LocalDate fechaActual = LocalDate.now(); 
        DateTimeFormatter formatter = DateTimeFormatter.ofPattern("dd/MM/yyyy"); 
        String fechaFormateada = fechaActual.format(formatter);

        long tiempoUnix = Instant.now().getEpochSecond();

        jLabel1.setText("Fecha: " + fechaFormateada + " | UNIX: " + tiempoUnix + " segundos");
    }

    public void cambiarIcono() {
        String ICON_PATH = "/ejercicioFinal/img/iconApp.png"; 
        URL iconUrl = getClass().getResource(ICON_PATH);
        if (iconUrl != null) {
            setIconImage(new ImageIcon(iconUrl).getImage());
        } else {
            logger.warning("No se pudo cargar el icono: " + ICON_PATH);
        }
    }
    
