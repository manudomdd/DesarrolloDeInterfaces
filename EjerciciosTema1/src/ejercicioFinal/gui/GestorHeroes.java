    private void jButton1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jButton1ActionPerformed
        // TODO add your handling code here:
        String nombreHeroe = javax.swing.JOptionPane.showInputDialog(rootPane, "Introduzca el nombre del heroe a eliminar: "); 

        for (int i = 0; i < model.getRowCount(); i++) {
            String nombre = model.getValueAt(i, 0).toString(); 
            if (nombre.equalsIgnoreCase(nombreHeroe)) {
                int option = javax.swing.JOptionPane.showConfirmDialog(rootPane, "¿Estás seguro de que quieres eliminar el héroe " + nombre + "?"); 
                switch (option) {
                    case 0: model.removeRow(i);
                    case 1: break; 
                }
            }
        }
    }//GEN-LAST:event_jButton1ActionPerformed

    private void initComboBox() {
        dcm = new DefaultComboBoxModel(); 
        for (LookAndFeelInfo lfi : UIManager.getInstalledLookAndFeels()) {
            dcm.addElement(lfi.getName());
        }
        dcm.addElement("Flat Light");
        dcm.addElement("Flat Night");  
        jComboBox1.setModel(dcm);
    }
    
    private void jComboBox1ActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_jComboBox1ActionPerformed
        // TODO add your handling code here:
        String lookAndFeelName = (String) jComboBox1.getSelectedItem();
        try {
            if (lookAndFeelName.equals("Flat Light")) {
                UIManager.setLookAndFeel(new FlatLightLaf());
            } else if (lookAndFeelName.equals("Flat Night")) {
                UIManager.setLookAndFeel(new FlatDarkLaf());   
            } else {
                for (UIManager.LookAndFeelInfo info : UIManager.getInstalledLookAndFeels()) {
                    if (info.getName().equals(lookAndFeelName)) {
                        UIManager.setLookAndFeel(info.getClassName());
                        break;
                    }
                }
            }
            javax.swing.SwingUtilities.updateComponentTreeUI(this);
            this.pack();
        } catch (Exception ex) {
            ex.printStackTrace();
        }    
    }//GEN-LAST:event_jComboBox1ActionPerformed

