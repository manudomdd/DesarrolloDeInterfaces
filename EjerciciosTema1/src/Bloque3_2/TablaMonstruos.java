    private void generarMonstruos() {
        String[] nombres = {"Draco", "Hydra", "Goblin", "Troll", "Fénix", "Vampiro", "Golem", "Kraken", "Quimera", "Basilisco"};
        String[] tipos = {"Dragón", "Gigante", "Humanoide", "Bestia", "No-muerto", "Elemental"};

        for (int i = 0; i < 10; i++) {
            int indiceNombre = (int) (Math.random() * nombres.length);
            int indiceTipo = (int) (Math.random() * tipos.length);
            int poder = (int) (Math.random() * 100);

            String nombre = nombres[indiceNombre];
            String tipo = tipos[indiceTipo];

            Object[] row = {nombre, tipo, poder};
            model.addRow(row);
        }
    }
    
    

