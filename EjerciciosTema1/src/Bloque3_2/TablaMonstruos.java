    public void initSorter() {
        sorter = new TableRowSorter<>(jTable1.getModel());
        jTable1.setRowSorter(sorter);
        
        sorter.setComparator(2, (o1, o2) -> {
            Integer num1 = Integer.parseInt(o1.toString());
            Integer num2 = Integer.parseInt(o2.toString());
            return num1.compareTo(num2);
        });
        
        sorter.setSortKeys(Arrays.asList(
            new RowSorter.SortKey(2, SortOrder.DESCENDING)
        ));
        sorter.sort();      
    }
    
    private void addTableClickListener() {
        jTable1.addMouseListener(new java.awt.event.MouseAdapter() {
            @Override
            public void mouseClicked(java.awt.event.MouseEvent evt) {
                int column = jTable1.getColumnModel().getColumnIndexAtX(evt.getX());
                
                if (column == 2 && model.getRowCount() > 0) {
                    mostrarMonstruoMasFuerte();
                }
            }
        });
    }
    
    private void mostrarMonstruoMasFuerte() {
        if (model.getRowCount() == 0) {
            JOptionPane.showMessageDialog(this, 
                "No hay monstruos en la tabla", 
                "Tabla vacía", 
                JOptionPane.INFORMATION_MESSAGE);
            return;
        }
        
        int maxPoder = -1;
        String nombreMasFuerte = "";
        String tipoMasFuerte = "";
        
        for (int i = 0; i < model.getRowCount(); i++) {
            int poder = Integer.parseInt(model.getValueAt(i, 2).toString());
            if (poder > maxPoder) {
                maxPoder = poder;
                nombreMasFuerte = model.getValueAt(i, 0).toString();
                tipoMasFuerte = model.getValueAt(i, 1).toString();
            }
        }
        
        String mensaje = String.format(
            "🏆 MONSTRUO MAS FUERTE 🏆\n\n" +
            "Nombre: %s\n" +
            "Tipo: %s\n" +
            "Poder: %d",
            nombreMasFuerte, tipoMasFuerte, maxPoder
        );
        
        JOptionPane.showMessageDialog(this, 
            mensaje, 
            "Monstruo mas Fuerte", 
            JOptionPane.INFORMATION_MESSAGE);
    }
        
